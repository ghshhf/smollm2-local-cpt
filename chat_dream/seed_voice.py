def norm_q(q):
    return re.sub(r"[^\u4e00-\u9fffA-Za-z0-9]", "", q).lower()


def main():
    c = sqlite3.connect(DB, timeout=30)
    ins = skip = 0
    for q, a, tp in SEEDS:
        k = norm_q(q)
        if not k:
            continue
        try:
            c.execute("INSERT INTO seeds(q,a,q_key,topic) VALUES(?,?,?,?)", (q, a, k, tp))
            ins += 1
        except sqlite3.IntegrityError:
            skip += 1
    c.commit()
    print(f"新增种子 {ins} 条 | 已存在跳过 {skip} 条")
    print("=== 种子区分布 ===")
    for t, n in c.execute("select topic,count(*) from seeds group by topic order by 2 desc"):
        print(f"  {t:9s} {n}")
    print("总数:", c.execute("select count(*) from seeds").fetchone()[0])

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "seed_voice.json")
    json.dump([{"q": q, "a": a, "topic": t} for q, a, t in SEEDS],
              open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("已写出", out)
    c.close()


if __name__ == "__main__":
    main()
