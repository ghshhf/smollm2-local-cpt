def wrap(q, a):
    return {"text": "<|im_start|>user\n%s<|im_end|>\n<|im_start|>assistant\n%s<|im_end|>" % (q, a)}


def is_dirty(text):
    """空问题 / 无 assistant 段 / 无 user 段"""
    return bool(re.search(r"<\|im_start\|>user\n<\|im_end\|>", text))


def main():
    out, seen_q = [], set()

    # 1) 保留 v1（去脏、去重）
    n_keep = n_drop = 0
    for line in open(SRC, encoding="utf-8"):
        r = json.loads(line)
        t = r["text"]
        if is_dirty(t):
            n_drop += 1
            continue
        m = re.search(r"user\n(.*?)<\|im_end\|>", t)
        q = (m.group(1).strip() if m else "")[:60]
        if q in seen_q:
            n_drop += 1
            continue
        seen_q.add(q)
        out.append(r)
        n_keep += 1

    # 2) 新增日常对话（与 v1 问题去重）
    n_new = 0
    for q, a in D:
        if q in seen_q:
            continue
        seen_q.add(q)
        out.append(wrap(q, a))
        n_new += 1

    with open(DST, "w", encoding="utf-8") as f:
        for r in out:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    # 3) 统计
    n_code = sum(1 for r in out if any(k in r["text"] for k in ("```", "def ", "import ", "function")))
    print("[v2] 保留 %d（剔脏/重复 %d）+ 新增 %d = %d 条" % (n_keep, n_drop, n_new, len(out)))
    print("     代码 %d | 非代码(闲聊为主) %d —— 闲聊占比 %.0f%%" % (
        n_code, len(out) - n_code, 100 * (len(out) - n_code) / len(out)))
    lens = [len(re.search(r"assistant\n(.*?)<\|im_end\|>", r["text"], re.S).group(1)) for r in out]
    print("     回复长度 中位 %d | max %d" % (sorted(lens)[len(lens) // 2], max(lens)))


if __name__ == "__main__":
    main()
