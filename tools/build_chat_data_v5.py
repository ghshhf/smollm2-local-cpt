def main():
    lines = []
    for ln in open(SRC, encoding="utf-8"):
        d = json.loads(ln)
        lines.append(d["text"])

    seen = set()
    uniq = []
    for t in lines:
        u = re.search(r"<\|im_start\|>user\n(.*?)<\|im_end\|>", t, re.S)
        a = re.search(r"<\|im_start\|>assistant\n(.*?)<\|im_end\|>", t, re.S)
        key = (u.group(1) if u else "", a.group(1) if a else "")
        if key in seen:
            continue
        seen.add(key)
        uniq.append(t)

    added = 0
    for t in NEW:
        u = re.search(r"<\|im_start\|>user\n(.*?)<\|im_end\|>", t, re.S)
        a = re.search(r"<\|im_start\|>assistant\n(.*?)<\|im_end\|>", t, re.S)
        key = (u.group(1) if u else "", a.group(1) if a else "")
        if key in seen:
            continue
        seen.add(key)
        uniq.append(t)
        added += 1

    assert not any("助手" in t for t in uniq), "语料里混入助手腔！"

    # 用户 2026-10-17 定调：对话数据禁重复，重复=过拟合，压缩才是正道。
    # 身份事实不靠同一条复制 xN 注入，而是已用 ~25 条不同问法/表述各出现一次
    # （压缩式注入：信息保留、形式多样，零逐字重复）。
    out = list(uniq)

    with open(DST, "w", encoding="utf-8") as f:
        for t in out:
            f.write(json.dumps({"text": t}, ensure_ascii=False) + "\n")

    print(f"唯一对话: {len(uniq)} 条（新增 {added}，零重复）-> {DST}")

if __name__ == "__main__":
    main()
